// Ordered groups used to render <optgroup> blocks in category dropdowns.
export const GIG_CATEGORY_GROUPS = GIG_TAXONOMY.reduce((groups, item) => {
  let group = groups.find((entry) => entry.group === item.group);
  if (!group) {
    group = { group: item.group, categories: [] };
    groups.push(group);
  }
  group.categories.push(item.category);
  return groups;
}, []);

export const GIG_CATEGORIES = GIG_TAXONOMY.map((item) => item.category);

export const GIG_SUBCATEGORIES = GIG_TAXONOMY.reduce((map, item) => {
  map[item.category] = item.subcategories;
  return map;
}, {});

export const getGigSubcategories = (category) => GIG_SUBCATEGORIES[category] || [];

